import fs from 'node:fs';
import assert from 'node:assert/strict';
const feed=fs.readFileSync('site/chanse3/social-feed.js','utf8');
const rules=fs.readFileSync('FIRESTORE-RULES-v238.rules','utf8');
const siteRules=fs.readFileSync('site/FIRESTORE-RULES-v238.rules','utf8');
const channelRules=fs.readFileSync('site/chanse4/FIRESTORE-RULES-v238.rules','utf8');
const mirror=fs.readFileSync('source/The-Squad-v137/chanse3/social-feed.js','utf8');
const siteFeed=fs.readFileSync('site/chanse3/social-feed.js','utf8');
const auth=fs.readFileSync('site/chanse1/auth.js','utf8');
const version=JSON.parse(fs.readFileSync('site/version.json','utf8'));
const sw=fs.readFileSync('site/sw.js','utf8');
assert.equal(mirror,siteFeed,'source and deployed social-feed mirrors must match');
assert.equal(siteRules,rules,'site rules copy must match release rules');
assert.equal(channelRules,rules,'channel rules copy must match release rules');
assert.match(feed,/type:'post_like'/,'new likes must create owner notifications');
assert.match(feed,/type:'post_comment'/,'new comments must create owner notifications');
assert.match(feed,/owner!==me/,'do not notify users about their own interactions');
assert.match(feed,/status!=='published'/,'interactions must reject unavailable posts');
assert.match(rules,/request\.resource\.data\.type in \['post_like','post_comment'\]/,'rules must explicitly allow supported post notifications');
assert.match(rules,/\.data\.authorUid == ownerUid/,'notification target must own the referenced post');
assert.match(rules,/\.data\.status == 'published'/,'notification must reference a published post');
assert.ok(auth.includes('sendPasswordResetEmail'),'password recovery remains available');
assert.ok(auth.includes('signInWithEmailAndPassword'),'email sign-in remains available');
assert.ok(auth.includes('createUserWithEmailAndPassword'),'account creation remains available');
assert.ok(version.build>=241);
assert.equal(version.version,`v${version.build}-${version.featureName}`);
assert.ok(sw.includes('v238-social-interaction-notifications'));
console.log('v238 social interaction notification checks passed.');
