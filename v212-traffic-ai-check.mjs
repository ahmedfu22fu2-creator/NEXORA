import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const coreSource=fs.readFileSync(new URL('../site/chanse1/district-core.js',import.meta.url),'utf8');
const sandbox={module:{exports:{}},exports:{}};
vm.runInNewContext(coreSource,sandbox,{filename:'district-core.js'});
const DC=sandbox.module.exports;
assert.equal(typeof DC.trafficStep,'function','traffic AI exported from deterministic city core');
const route=(pos,speed=10)=>({axis:'x',lane:3.25,pos,dir:1,min:-100,max:100,speed,currentSpeed:speed,braking:false});
const following=[route(0,10),route(12,10)];
DC.trafficStep(following,.05,null);
assert.ok(following[0].currentSpeed<10,'following vehicle slows when headway is short');
assert.equal(following[0].braking,true,'following vehicle reports active braking');
assert.ok(following[1].currentSpeed<=10,'lead vehicle remains within cruise speed');
const open=[route(0,10)];
DC.trafficStep(open,.05,null);
assert.equal(open[0].currentSpeed,10,'unobstructed traffic maintains cruise speed');
const playerYield=[route(0,10)];
DC.trafficStep(playerYield,.05,{x:9,z:3.25,yaw:-Math.PI/2,v:0});
assert.ok(playerYield[0].currentSpeed<10,'traffic yields to a stopped player vehicle on its lane');
const reverseLane=[{...route(0,10),dir:-1},{...route(12,10),dir:1}];
DC.trafficStep(reverseLane,.05,null);
assert.equal(reverseLane[0].currentSpeed,10,'opposing lanes do not incorrectly follow one another');
const src=fs.readFileSync(new URL('../site/chanse2/district.js',import.meta.url),'utf8');
assert.match(src,/DC\.trafficStep\(AMBIENT_TRAFFIC,dt,DRV\)/);
assert.match(src,/currentSpeed:r\.speed,braking:false/);
console.log('v212 traffic AI checks: PASS — adaptive headway, braking, player-vehicle yielding, lane direction isolation.');
