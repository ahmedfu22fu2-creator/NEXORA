import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('site/index.html'),css=read('site/v205-visual-expansion.css'),js=read('site/v205-visual-expansion.js'),sw=read('site/sw.js');
assert.match(html,/<link rel="stylesheet" href="v205-visual-expansion\.css">/);
assert.match(html,/<script src="v205-visual-expansion\.js" defer><\/script>/);
assert.ok(html.indexOf('v205-visual-expansion.css')>html.indexOf('v192-login-lamp-restore.css'),'v205 must be final style override');
assert.ok(html.indexOf('v205-visual-expansion.js')>html.indexOf('v203-design-system.js'),'v205 runtime must load after base design system');
for(const f of ['v205-visual-expansion.css','v205-visual-expansion.js'])assert.ok(sw.includes(`"${f}"`),`precache includes ${f}`);
for(const selector of ['#social-shell','#social-rail.sq195-rail','#social-main .dr-top','#social-aside .dr-side-card','#dr-screen .dr-post','.sq165-hero','.sq165-tile','#side','#chat .cv','.dr-mobile-nav'])assert.ok(css.includes(selector),`visual coverage ${selector}`);
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/max-width:760px/);
assert.match(css,/max-width:420px/);
assert.doesNotMatch(js,/fetch\(|XMLHttpRequest|localStorage|sessionStorage|firebase|eval\(/,'presentation runtime must not write data or call services');
const list=JSON.parse(sw.match(/const F=(\[[\s\S]*?\]);/)[1]);
for(const f of list)if(f!=='./')assert.ok(fs.existsSync(`site/${f}`),`precache exists: ${f}`);
const v=JSON.parse(read('site/version.json'));
assert.ok(v.build>=206);assert.equal(v.version,`v${v.build}-${v.featureName}`);
assert.deepEqual(v,JSON.parse(read('site/chanse4/version.json')));
assert.ok(Number.parseInt(JSON.parse(read('package.json')).version,10)>=241);
console.log(`V205 VISUAL EXPANSION CHECK PASSED — auth, workspace, social, universe, messenger and mobile design coverage; ${list.length} precache assets valid.`);
