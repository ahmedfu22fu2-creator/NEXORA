import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('site/index.html');
const css=read('site/v219-brand-system.css');
const manifest=JSON.parse(read('site/chanse1/manifest.json'));
assert.match(html,/<title>NEXORA/);
assert.match(html,/v219-brand-system\.css/);
assert.match(css,/--squad-bg:#0B0C10/);
assert.match(css,/--squad-ivory:#F5F5F7/);
assert.match(css,/--squad-accent:#D4AF37/);
assert.match(css,/--squad-radius-md:14px/);
assert.equal(manifest.background_color,'#0B0C10');
assert.equal(manifest.theme_color,'#0B0C10');
for(const file of ['site/chanse1/icon-192.png','site/chanse1/icon-512.png','site/chanse1/icon-maskable-512.png','site/chanse3/icon-192.png','site/chanse3/icon-512.png','site/chanse3/icon-maskable-512.png','site/chanse2/apple-touch-icon.png']) assert.ok(fs.statSync(path.join(root,file)).size>1000,`${file} missing or empty`);
assert.match(read('site/chanse4/icon.svg'),/#D4AF37/);
console.log('v219 brand identity checks: PASS');
