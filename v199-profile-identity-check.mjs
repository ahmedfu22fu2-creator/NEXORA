import fs from 'node:fs';
import assert from 'node:assert/strict';
const site='site/';
const html=fs.readFileSync(site+'index.html','utf8');
const js=fs.readFileSync(site+'v199-squad-identity.js','utf8');
const css=fs.readFileSync(site+'v199-squad-identity.css','utf8');
const version=JSON.parse(fs.readFileSync(site+'version.json','utf8'));
assert.match(html,/v199-squad-identity\.css/,'profile CSS is linked');
assert.match(html,/v199-squad-identity\.js/,'profile JS is linked');
assert.ok(fs.existsSync(site+'v199-squad-identity.css'));
assert.ok(fs.existsSync(site+'v199-squad-identity.js'));
assert.ok(version.build>=206);
assert.equal(version.channel,`squad-v${version.build}`);
assert.match(js,/dr-profile-cover/,'enhancement attaches to existing profile route');
assert.match(js,/profileStats|dr-profile-stats/,'uses current social profile statistics');
assert.match(js,/data-sq199-action="settings"/,'links to existing account settings');
assert.doesNotMatch(js,/\.collection\([^)]*\)\.add\(|\.set\(|\.update\(/,'does not write new profile data');
assert.match(css,/@media\(max-width:680px\)/,'mobile layout exists');
assert.match(css,/prefers-reduced-motion/,'reduced-motion preference is respected');
console.log('v199 Squad Identity checks: PASS');
