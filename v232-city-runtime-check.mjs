import fs from 'node:fs';
import assert from 'node:assert/strict';
const world=fs.readFileSync('site/chanse2/world.js','utf8');
const version=JSON.parse(fs.readFileSync('site/version.json','utf8'));
const mirror=JSON.parse(fs.readFileSync('site/chanse4/version.json','utf8'));
const sw=fs.readFileSync('site/sw.js','utf8');
assert.match(world,/function startWorldLoop\(\)/,'world loop must have a guarded start helper');
assert.match(world,/function stopWorldLoop\(\)/,'world loop must have a stop helper');
assert.match(world,/if\(!openW\|\|document\.hidden\|\|worldPaused\)return/,'hidden or closed world must not keep rendering');
assert.match(world,/worldFrameCount\+\+.*fps/s,'world must monitor frame rate');
assert.match(world,/ren\.setPixelRatio\(next\)/,'world must adapt render resolution');
assert.match(world,/webglcontextlost/,'world must handle WebGL context loss');
assert.match(world,/webglcontextrestored/,'world must resume after WebGL context restoration');
assert.match(world,/document\.addEventListener\('visibilitychange'/,'world must pause/resume on tab visibility');
assert.ok(version.currentPhase >= 232,'current release must include v232 or later');
if(version.currentPhase===232) assert.equal(version.currentFeatureName,'3d-city-runtime-performance-and-recovery');
assert.deepEqual(mirror,version,'version mirrors must stay identical');
assert.match(sw,/v232-city-runtime-recovery/,'service worker cache namespace must be refreshed');
console.log('v232 city runtime checks passed');
