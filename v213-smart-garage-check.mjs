import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const coreSource=read('../site/chanse1/district-core.js');
const sandbox={module:{exports:{}},exports:{}};
vm.runInNewContext(coreSource,sandbox,{filename:'district-core.js'});
const DC=sandbox.module.exports;
assert.equal(typeof DC.garageRampHeight,'function','garage ramp height is exposed by deterministic core');
const garage=DC.MAP.buildings.find(b=>b.id==='garage');
assert.ok(garage&&garage.n===3,'the original three-level garage remains present');
// Garage side is mirrored (dir=-1): these world coordinates map to local u=-9.5 / +9.5.
const lower=DC.garageRampHeight(garage.cx+9.5,garage.cz+0.5);
const upper=DC.garageRampHeight(garage.cx-9.5,garage.cz+0.5);
assert.ok(Math.abs(lower-garage.fh/2)<.001,'first ramp rises continuously from ground to level 2');
assert.ok(Math.abs(upper-garage.fh*1.5)<.001,'second ramp rises continuously from level 2 to level 3');
assert.ok(Math.abs(DC.groundAt(garage.cx+9.5,garage.cz+0.5,lower+.2)-lower)<.001,'vehicle ground height follows the first ramp');
assert.ok(Math.abs(DC.groundAt(garage.cx-9.5,garage.cz+0.5,upper+.2)-upper)<.001,'vehicle ground height follows the second ramp');
assert.equal(DC.garageRampHeight(garage.cx,garage.cz),null,'garage center remains a flat parking/circulation area');
const testCar=DC.spawnCar('rr',garage.cx+9.5,garage.cz+9.5,0);
DC.carHold(testCar,true);
for(let i=0;i<500;i++)DC.drive(testCar,{f:1,s:0,b:false},.05);
assert.ok(testCar.y>=garage.fh-.05,'a player vehicle can physically climb from ground to level two');
const upperCar=DC.spawnCar('rr',garage.cx-9.5,garage.cz-8.5,Math.PI);
upperCar.y=garage.fh;DC.carHold(upperCar,true);
for(let i=0;i<500;i++)DC.drive(upperCar,{f:1,s:0,b:false},.05);
assert.ok(upperCar.y>=garage.fh*2-.05,'a player vehicle can physically climb from level two to level three');
const core=coreSource,city=read('../site/chanse2/district.js');
assert.match(core,/H\(1\)\.push\(\{ u0: -11\.7, u1: -7\.3/,'first ramp has a slab aperture');
assert.match(core,/H\(2\)\.push\(\{ u0: 7\.3, u1: 11\.7/,'second ramp has a slab aperture');
assert.match(core,/const u=-6\+col\*3,v=-6\+row\*12/,'parking bays are clear of the outer ramp lanes');
assert.match(city,/addRamp\(-9\.5,-9\.5,8\.5,0,fh\)/,'first visible ramp is rendered');
assert.match(city,/addRamp\(9\.5,8\.5,-9\.5,fh,fh\*2\)/,'second visible ramp is rendered');
assert.match(city,/function garageReserve\(/,'parking reservations are available');
assert.match(city,/squad_garage_reservation_v213_/,'parking reservation is stored per account/device');
assert.match(city,/data-garage-slot/,'parking bay controls are rendered');
const v=JSON.parse(read('../site/version.json')),pkg=JSON.parse(read('../package.json')),sw=read('../site/sw.js');
assert.ok(v.build>=241);assert.equal(v.version,`v${v.build}-${v.featureName}`);assert.ok(Number.parseInt(pkg.version,10)>=241);assert.match(sw,/squad-v235-property-room-design-cloud/);
assert.equal(city,read('../source/The-Squad-v137/chanse2/district.js'),'city source mirror');
assert.equal(core,read('../source/The-Squad-v137/chanse1/district-core.js'),'core source mirror');
console.log('v213 smart garage checks: PASS — two continuous ramp profiles, upper-floor slab openings, visual ramps, 30 parking bays, preserved ramp physics and v214 release metadata.');
