import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('site/index.html','utf8');
const cinema=fs.readFileSync('site/chanse4/cinema.js','utf8');
const universe=fs.readFileSync('site/v165-squad-universe.js','utf8');
const auth=fs.readFileSync('site/chanse1/auth.js','utf8');
const app=fs.readFileSync('site/chanse1/app.js','utf8');
assert.match(cinema,/function initCinema\(root\)/,'cinema initialization must be scoped to an existing world');
assert.match(cinema,/new MutationObserver\(\(\)=>findWorld\(\)\)/,'cinema must wait for lazy world creation');
assert.match(cinema,/if\(!findWorld\(\)\)/,'cinema must handle the world not existing at initial page load');
assert.match(universe,/function open\(t\)/,'Universe root must be created by open()');
const openStart=universe.indexOf('function open(t)');
const listenerPos=universe.indexOf("root.addEventListener('submit'");
const launcherPos=universe.indexOf('function launcher()');
assert.ok(listenerPos>openStart&&listenerPos<launcherPos,'submit listener must be attached only while creating the Universe root');
assert.ok(!universe.slice(0,openStart).includes("root.addEventListener('submit'"),'no top-level submit listener may dereference a null root');
assert.match(html,/v188 hotfix: delayed Cinema initialization/);
assert.match(html,/v188 hotfix: create Universe event handlers only after its root exists/);
assert.ok(!/<script[^>]+src=["'](?:chanse4\/cinema\.js|v165-squad-universe\.js)/i.test(html),'fixed modules must not be loaded again as external scripts');
assert.match(auth,/signInWithEmailAndPassword\(raw\+'@squad\.id',pw\)/,'legacy account-number sign-in must use its synthetic Firebase email');
assert.match(auth,/httpsCallable\('usernameLogin'\)/,'username sign-in must retain its server-verified callable');
assert.match(auth,/signInWithEmailAndPassword/,'email sign-in must remain wired');
assert.match(app,/firebase\.initializeApp\(squadFirebaseConfig/,'Firebase initialization must remain intact');
assert.match(app,/firebase\.apps\s*\|\|\s*\[\]/,'Firebase startup must reuse an existing app instead of duplicating initialization');
assert.match(html,/chanse4\/firebase-config\.js/,'Firebase config must remain loaded');
console.log('V188 STARTUP REPAIR CHECK PASSED — deferred cinema startup, safe Universe listeners, single-file inline delivery, and auth/Firebase wiring retained.');
