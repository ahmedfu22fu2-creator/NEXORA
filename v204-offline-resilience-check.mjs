import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const sw=read('site/sw.js');
const html=read('site/index.html');
const a=JSON.parse(read('site/version.json'));
const b=JSON.parse(read('site/chanse4/version.json'));
const pkg=JSON.parse(read('package.json'));
const sitePkg=JSON.parse(read('site/package.json'));
assert.ok(a.build>=206);
assert.equal(a.version,`v${a.build}-${a.featureName}`);
assert.equal(a.channel,`squad-v${a.build}`);
assert.deepEqual(a,b,'root and legacy release manifests must be identical');
assert.ok(Number.parseInt(pkg.version,10)>=241);
assert.ok(Number.parseInt(sitePkg.version,10)>=241);
assert.match(sw,/squad-v235-property-room-design-cloud/);
assert.doesNotMatch(sw,/squad-v203-design-system/);
assert.match(sw,/new AbortController\(\)/,'navigation fetch must be abortable');
assert.match(sw,/page\?4500:2500/,'navigation and manifest network windows must be bounded');
assert.match(sw,/caches\.match\(request\)/,'failed network request must use its cached response');
assert.match(sw,/await caches\.match\('index\.html'\)/,'offline navigation must fall back to the cached home page');
assert.match(sw,/You are offline/,'first-run offline state must explain recovery');
assert.match(sw,/finally\{clearTimeout\(timeout\)\}/,'network timeout must always be cleared');
assert.match(html,/v203-design-system\.js/,'v203 design-system runtime must remain wired');
const list=JSON.parse(sw.match(/const F=(\[[\s\S]*?\]);/)[1]);
for(const f of list)if(f!=='./')assert.ok(fs.existsSync(`site/${f}`),`missing precache asset ${f}`);
console.log(`V204 OFFLINE RESILIENCE REGRESSION CHECK PASSED — bounded navigation recovery, cached fallback, first-run offline explanation, synced release metadata, ${list.length} precache assets.`);
