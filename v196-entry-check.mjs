import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const site=path.join(root,'site');
const read=p=>fs.readFileSync(path.join(site,p),'utf8');
const nav=read('v196-premium-navigation.js');
const index=read('index.html');
const sw=read('sw.js');
const ai=read('chanse3/ai-hub.html');
const store=read('chanse3/store.html');
const meta=JSON.parse(read('version.json'));
assert.match(index,/v196-premium-navigation\.js/,'main entry loads v196 navigation');
assert.match(nav,/ai-hub\.html/,'AI route has dedicated page');
assert.match(nav,/store\.html/,'Store route has dedicated page');
assert.match(nav,/version:197/,'navigation reports v197 while retaining v196 routes');
assert.match(sw,/squad-v235-property-room-design-cloud/,'service worker cache namespace is v197');
for(const p of ['v196-premium-navigation.js','chanse3/ai-hub.html','chanse3/store.html']) assert.ok(sw.includes(p),`service worker precaches ${p}`);
assert.ok(meta.build>=206);
assert.equal(meta.version,`v${meta.build}-${meta.featureName}`);
assert.match(ai,/https:\/\/chatgpt\.com\//);
assert.match(ai,/https:\/\/claude\.ai\//);
assert.match(ai,/https:\/\/gemini\.google\.com\//);
assert.match(ai,/navigator\.clipboard\.writeText/);
assert.match(ai,/لا يتم إرسال النص تلقائيًا/);
assert.match(store,/economyGet/);
assert.match(store,/economyAction/);
assert.match(store,/السعر والملكية لا يعتمدان على بيانات المتصفح/);
assert.match(store,/لا توجد مدفوعات بنكية أو تحويلات أموال حقيقية مفعّلة/);
console.log('V196 COMPATIBILITY CHECK PASSED — dedicated AI and Store pages, honest integration boundaries, navigation, metadata and cache verified.');
